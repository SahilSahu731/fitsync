problems AS (
 SELECT 'missing_table' AS problem, name AS object FROM expected_tables WHERE to_regclass('public.'||name) IS NULL
 UNION ALL SELECT 'row_security_disabled', e.name FROM expected_tables e JOIN pg_class c ON c.oid=to_regclass('public.'||e.name) WHERE NOT c.relrowsecurity
 UNION ALL SELECT 'missing_service_access',e.name FROM expected_tables e JOIN pg_class c ON c.oid=to_regclass('public.'||e.name) WHERE EXISTS(SELECT 1 FROM unnest(ARRAY['SELECT','INSERT','UPDATE','DELETE']) privilege WHERE NOT has_table_privilege('service_role',c.oid,privilege))
 UNION ALL SELECT 'missing_index',name FROM expected_indexes WHERE NOT EXISTS(SELECT 1 FROM pg_index WHERE indexrelid=to_regclass('public.'||name))
 UNION ALL SELECT 'missing_function',e.name FROM expected_functions e WHERE NOT EXISTS(SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace WHERE n.nspname='public' AND p.proname=e.name)
 UNION ALL SELECT 'unexpected_function_access',p.proname FROM expected_functions e JOIN pg_proc p ON p.proname=e.name JOIN pg_namespace n ON n.oid=p.pronamespace WHERE n.nspname='public' AND (has_function_privilege('anon',p.oid,'EXECUTE') OR has_function_privilege('authenticated',p.oid,'EXECUTE'))
 UNION ALL SELECT 'missing_column',e.table_name||'.'||e.column_name FROM expected_columns e WHERE NOT EXISTS(SELECT 1 FROM information_schema.columns c WHERE c.table_schema='public' AND c.table_name=e.table_name AND c.column_name=e.column_name)
 UNION ALL SELECT 'missing_trigger',e.table_name||'.'||e.name FROM expected_triggers e WHERE NOT EXISTS(SELECT 1 FROM pg_trigger t WHERE t.tgrelid=to_regclass('public.'||e.table_name) AND t.tgname=e.name AND t.tgenabled IN ('O','A'))
 UNION ALL SELECT 'missing_curated_resource',e.slug FROM expected_slugs e WHERE NOT EXISTS(SELECT 1 FROM public.explore_resources r WHERE r.slug=e.slug)
)
SELECT problem,object FROM problems
UNION ALL SELECT 'missing_function_signature',signature FROM expected_signatures WHERE to_regprocedure('public.'||signature) IS NULL
UNION ALL SELECT 'invalid_index',c.relname FROM pg_index i JOIN pg_class c ON c.oid=i.indexrelid JOIN expected_indexes e ON e.name=c.relname WHERE NOT i.indisvalid
UNION ALL SELECT 'unvalidated_constraint',c.conrelid::regclass::text||'.'||c.conname FROM pg_constraint c JOIN pg_namespace n ON n.oid=c.connamespace WHERE n.nspname='public' AND NOT c.convalidated
UNION ALL SELECT 'unsafe_catalog_view','exercise_catalog' WHERE NOT coalesce((SELECT reloptions @> ARRAY['security_invoker=true'] FROM pg_class WHERE oid=to_regclass('public.exercise_catalog')),false)
UNION ALL SELECT 'incorrect_created_by_fk','exercises_created_by_fkey' WHERE NOT coalesce((SELECT condeferrable AND condeferred FROM pg_constraint WHERE conrelid=to_regclass('public.exercises') AND conname='exercises_created_by_fkey'),false)
UNION ALL SELECT 'incorrect_coaching_date_constraint','coaching_unique_date' WHERE NOT coalesce((SELECT condeferrable AND condeferred FROM pg_constraint WHERE conrelid=to_regclass('public.coaching_days') AND conname='coaching_unique_date'),false)
UNION ALL SELECT 'missing_advanced_set_constraint',e.table_name FROM (VALUES ('workout_template_sets'),
  ('workout_logged_sets')) e(table_name) WHERE NOT EXISTS(SELECT 1 FROM pg_constraint c WHERE c.conrelid=to_regclass('public.'||e.table_name) AND c.conname=e.table_name||'_set_type_check' AND pg_get_constraintdef(c.oid) LIKE '%rest_pause%')
UNION ALL SELECT 'incorrect_private_bucket',e.name FROM (VALUES ('profile-images'),
  ('progress-photos')) e(name) WHERE NOT EXISTS(SELECT 1 FROM storage.buckets b WHERE b.id=e.name AND NOT b.public AND b.file_size_limit=3145728 AND b.allowed_mime_types=ARRAY['image/webp']::text[])
UNION ALL SELECT 'missing_exercise_bucket','exercise-images' WHERE NOT EXISTS(SELECT 1 FROM storage.buckets WHERE id='exercise-images' AND public AND file_size_limit=3145728 AND allowed_mime_types=ARRAY['image/webp']::text[])
UNION ALL SELECT 'unexpected_personal_table_access',e.name FROM expected_private_tables e JOIN pg_class c ON c.oid=to_regclass('public.'||e.name) WHERE has_table_privilege('anon',c.oid,'SELECT,INSERT,UPDATE,DELETE') OR has_table_privilege('authenticated',c.oid,'SELECT,INSERT,UPDATE,DELETE')
UNION ALL SELECT 'missing_service_rpc_access',signature FROM expected_signatures e JOIN pg_proc p ON p.oid=to_regprocedure('public.'||e.signature) WHERE p.prorettype<>'trigger'::regtype AND NOT has_function_privilege('service_role',p.oid,'EXECUTE')
UNION ALL SELECT 'missing_pgcrypto','pgcrypto' WHERE NOT EXISTS(SELECT 1 FROM pg_extension WHERE extname='pgcrypto')
UNION ALL SELECT 'incorrect_catalog_access','exercise_catalog' WHERE NOT coalesce(has_table_privilege('service_role',to_regclass('public.exercise_catalog'),'SELECT'),false) OR has_table_privilege('anon',to_regclass('public.exercise_catalog'),'SELECT') OR has_table_privilege('authenticated',to_regclass('public.exercise_catalog'),'SELECT')
ORDER BY problem,object;
