const schemaNotify = "NOTIFY pgrst, 'reload schema';";

// Split only outside SQL literals/comments, so function-body BEGIN/COMMIT stay intact.
function statements(sql) {
  const result = [];
  let start = -1;
  let quote = null;
  let blockDepth = 0;
  for (let i = 0; i < sql.length; i++) {
    if (blockDepth) {
      if (sql.startsWith("/*", i)) {
        blockDepth++;
        i++;
      } else if (sql.startsWith("*/", i)) {
        blockDepth--;
        i++;
      }
      continue;
    }
    if (quote) {
      if (!sql.startsWith(quote, i)) continue;
      if (quote.length === 1 && sql[i + 1] === quote) {
        i++;
        continue;
      }
      i += quote.length - 1;
      quote = null;
      continue;
    }
    if (sql.startsWith("--", i)) {
      const newline = sql.indexOf("\n", i);
      i = newline === -1 ? sql.length : newline;
      continue;
    }
    if (sql.startsWith("/*", i)) {
      blockDepth++;
      i++;
      continue;
    }
    if (/\s/.test(sql[i])) continue;
    if (start === -1) start = i;
    if (sql[i] === "'" || sql[i] === '"') quote = sql[i];
    else if (sql[i] === "$") {
      const delimiter = sql.slice(i).match(/^\$(?:[A-Za-z_][A-Za-z0-9_]*)?\$/)?.[0];
      if (delimiter) {
        quote = delimiter;
        i += delimiter.length - 1;
      }
    } else if (sql[i] === ";") {
      result.push({ start, end: i + 1, text: sql.slice(start, i + 1) });
      start = -1;
    }
  }
  if (quote || blockDepth || start !== -1)
    throw new Error("Unterminated SQL statement, literal or comment");
  return result;
}

export function stripMigration(sql, name) {
  const parsed = statements(sql);
  const hasNotify = parsed.at(-1)?.text === schemaNotify;
  const commitIndex = parsed.length - (hasNotify ? 2 : 1);
  if (parsed[0]?.text !== "BEGIN;" || parsed[commitIndex]?.text !== "COMMIT;") {
    throw new Error(
      `${name}: expected one BEGIN/COMMIT wrapper and optional trailing schema NOTIFY`,
    );
  }
  if (
    parsed
      .slice(1, commitIndex)
      .some(
        ({ text }) =>
          /^(BEGIN|COMMIT|ROLLBACK|START\s+TRANSACTION|END)\b/i.test(text) || text === schemaNotify,
      )
  ) {
    throw new Error(`${name}: unexpected nested transaction or schema NOTIFY`);
  }
  const wrappers = [parsed[0], parsed[commitIndex], ...(hasNotify ? [parsed.at(-1)] : [])];
  for (const { start, end } of wrappers) {
    if ((start > 0 && sql[start - 1] !== "\n") || (end < sql.length && sql[end] !== "\n")) {
      throw new Error(`${name}: wrapper must occupy an exact standalone line`);
    }
  }
  let body = sql;
  for (const { start, end } of [...wrappers].reverse())
    body = body.slice(0, start) + body.slice(end + (body[end] === "\n" ? 1 : 0));
  return body.trimEnd();
}

