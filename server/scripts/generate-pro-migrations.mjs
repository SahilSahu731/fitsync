export function renderBundle(migrations) {
  const hashes = migrations
    .map(({ name, sql }) => `-- SHA256 ${name}: ${createHash("sha256").update(sql).digest("hex")}`)
    .join("\n");
  const bodies = migrations
    .map(({ name, sql }) => `-- Source: ${name}\n${stripMigration(sql, name)}`)
    .join("\n\n");
  return `-- Generated by npm run db:generate. Do not edit this file directly.
-- FitSync Pro migrations 012–020, in numbered order, in one atomic transaction.
-- Apply baseline migrations 001–009 first; 010/011 are optional performance/content additions.
-- Run as the configured Supabase database owner. Existing account/workout records are preserved.
-- This creates storage and feature RPCs; it does not grant Pro access.
${hashes}
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '60s';
SELECT pg_advisory_xact_lock(hashtext('fitsync:pro-migrations'));
DO $$
DECLARE missing text;
BEGIN
  SELECT string_agg(name, ', ' ORDER BY name) INTO missing
  FROM unnest(ARRAY[
${prerequisites.map((name) => `    '${name}'`).join(",\n")}
  ]::text[]) AS required(name)
  WHERE to_regclass(name) IS NULL;
  IF missing IS NOT NULL THEN
    RAISE EXCEPTION 'Missing FitSync baseline prerequisites: %. Apply migrations 001–009 first.', missing;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.exercises'::regclass
    AND conname='exercises_created_by_fkey' AND contype='f' AND confrelid='public.app_users'::regclass) THEN
    RAISE EXCEPTION 'Missing baseline constraint exercises_created_by_fkey from migration 004.';
  END IF;
END $$;

${bodies}

-- Explicit service access for the append-only journal (standalone 012 relies on defaults).
GRANT ALL ON public.progress_events TO service_role;
${schemaNotify}
COMMIT;

-- Schema-only verification; this reads no personal records.
SELECT c.relname AS table_name, c.relrowsecurity AS row_security_enabled
FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
WHERE n.nspname='public' AND c.relname IN (
  'progress_events', 'billing_entitlements', 'billing_webhook_events',
  'coaching_plans', 'coaching_days', 'coaching_workouts', 'coaching_commands',
  'wellness_preferences', 'wellness_meal_plans', 'wellness_commitments', 'accountability_partners',
  'companion_records', 'companion_photos', 'companion_shares'
) ORDER BY c.relname;
`;
}

async function main() {
  const args = process.argv.slice(2);
  if (args.some((arg) => arg !== "--check"))
    throw new Error("Usage: node scripts/generate-pro-migrations.mjs [--check]");
  const migrations = await Promise.all(
    sources.map(async (name) => ({
      name,
      sql: await readFile(resolve(sqlDirectory, name), "utf8"),
    })),
  );
  const output = renderBundle(migrations);
  const target = resolve(sqlDirectory, "apply-pro-migrations.sql");
  if (args.includes("--check")) {
    if ((await readFile(target, "utf8")) !== output)
      throw new Error("Migration bundle is stale. Run npm run db:generate.");
    console.log("Pro migration bundle is current (012–020).");
  } else {
    await writeFile(target, output);
    console.log("Generated sql/apply-pro-migrations.sql (012–020).");
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  main().catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
